"""Firebird Designer Online - server sem dependências Python externas.
Não expõe serviço Firebird; cria .FDB temporário via Firebird Embedded 3.
"""
from __future__ import annotations
import json, os, re, tempfile, subprocess, threading, time
from collections import defaultdict, deque
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parent
IDENT = re.compile(r'^[A-Z][A-Z0-9_]{0,30}$')
TYPES = {'SMALLINT', 'INTEGER', 'BIGINT', 'VARCHAR', 'CHAR', 'DATE', 'TIME', 'TIMESTAMP',
         'NUMERIC', 'DECIMAL', 'FLOAT', 'DOUBLE PRECISION', 'BOOLEAN', 'BLOB SUB_TYPE TEXT'}
DELETE_ACTIONS = {'NO ACTION', 'CASCADE', 'SET NULL'}
LIMIT_BYTES = 2_000_000
SEM = threading.BoundedSemaphore(2)
RATES = defaultdict(deque)
RATE_LOCK = threading.Lock()

def ident(s):
    if not isinstance(s, str) or not IDENT.fullmatch(s.upper()):
        raise ValueError(f'Identificador inválido: {str(s)[:45]}. Use até 31 letras, números e _; comece por letra.')
    return '"' + s.upper() + '"'

def rawname(s):
    ident(s)
    return s.upper()

def n_int(x, low, high, label):
    try: n = int(x)
    except (ValueError, TypeError): raise ValueError(f'{label}: número inválido')
    if not low <= n <= high: raise ValueError(f'{label}: permitido entre {low} e {high}')
    return n

def dtype(f):
    name = str(f.get('type', 'VARCHAR')).upper()
    if name not in TYPES: raise ValueError('Tipo de campo não permitido: ' + name[:40])
    if name in {'VARCHAR', 'CHAR'}:
        return f'{name}({n_int(f.get("length", 80), 1, 8191, "Tamanho")})'
    if name in {'DECIMAL', 'NUMERIC'}:
        p = n_int(f.get('precision', 12), 1, 18, 'Precisão')
        s = n_int(f.get('scale', 2), 0, p, 'Escala')
        return f'{name}({p},{s})'
    return name

def default_sql(value):
    if value is None or str(value).strip() == '': return ''
    s = str(value).strip()
    if len(s) > 200: raise ValueError('Valor padrão muito longo')
    if s.upper() in {'CURRENT_DATE', 'CURRENT_TIME', 'CURRENT_TIMESTAMP', 'NULL', 'TRUE', 'FALSE'}:
        return ' DEFAULT ' + s.upper()
    if re.fullmatch(r'-?\d+(\.\d+)?', s): return ' DEFAULT ' + s
    return ' DEFAULT ' + "'" + s.replace("'", "''") + "'"

def sql_literal(v, f):
    if v is None or v == '': return 'NULL'
    ty = f.get('type', 'VARCHAR').upper()
    if ty in {'SMALLINT', 'INTEGER', 'BIGINT'}:
        if isinstance(v, bool) or not re.fullmatch(r'-?\d+', str(v)):
            raise ValueError('Valor inteiro inválido para ' + f['name'])
        return str(int(v))
    if ty in {'FLOAT', 'DOUBLE PRECISION', 'NUMERIC', 'DECIMAL'}:
        if isinstance(v, bool) or not re.fullmatch(r'-?\d+(\.\d+)?', str(v)):
            raise ValueError('Número inválido para ' + f['name'])
        return str(v)
    if ty == 'BOOLEAN':
        if str(v).lower() in {'true','1','sim'}: return 'TRUE'
        if str(v).lower() in {'false','0','não','nao'}: return 'FALSE'
        raise ValueError('Booleano inválido: ' + f['name'])
    if len(str(v)) > 10000: raise ValueError('Registro contém texto grande demais')
    return "'" + str(v).replace("'", "''") + "'"

def schema_sql(project, include_data=True):
    if not isinstance(project, dict): raise ValueError('Projeto inválido')
    tables = project.get('tables')
    if not isinstance(tables, list) or len(tables) > 70: raise ValueError('Máximo de 70 tabelas')
    charset = project.get('charset', 'UTF8')
    if charset not in {'UTF8', 'WIN1252', 'ISO8859_1', 'NONE'}: raise ValueError('Charset inválido')
    seen = set()
    lines = ['-- Firebird Designer Online | SQL Dialect 3 | Firebird 3.0', '-- Estrutura independente do caminho do banco', '']
    all_fields = {}
    total_rows = 0
    for tab in tables:
        name = rawname(tab.get('name'))
        if name in seen: raise ValueError('Tabela duplicada: ' + name)
        seen.add(name)
        fields = tab.get('fields', [])
        if not isinstance(fields, list) or not 1 <= len(fields) <= 120:
            raise ValueError('A tabela ' + name + ' precisa de 1 a 120 campos')
        fseen = set()
        parts = []
        for f in fields:
            fname = rawname(f.get('name'))
            if fname in fseen: raise ValueError('Campo duplicado: ' + fname)
            fseen.add(fname)
            p = '    ' + ident(fname) + ' ' + dtype(f)
            if f.get('identity'):
                if f.get('type') not in {'SMALLINT', 'INTEGER', 'BIGINT'}:
                    raise ValueError('IDENTITY só é permitida em campos inteiros')
                p += ' GENERATED BY DEFAULT AS IDENTITY'
            if not f.get('identity'): p += default_sql(f.get('defaultValue', ''))
            if f.get('required') or f.get('primary'): p += ' NOT NULL'
            parts.append(p)
        keys = [ident(f['name']) for f in fields if f.get('primary')]
        if keys: parts.append('    CONSTRAINT ' + ident('PK_' + name[:28]) + ' PRIMARY KEY (' + ', '.join(keys) + ')')
        lines.append('CREATE TABLE ' + ident(name) + ' (\n' + ',\n'.join(parts) + '\n);\n')
        all_fields[name] = {f['name'].upper(): f for f in fields}
    # Linhas primeiro: FKs adicionadas depois, para suportar referências entre tabelas.
    if include_data:
        for tab in tables:
            tname = rawname(tab['name']); fields = tab['fields']
            rows = tab.get('records', [])
            if not isinstance(rows, list) or len(rows) > 1000: raise ValueError('Até 1000 registros por tabela')
            total_rows += len(rows)
            if total_rows > 5000: raise ValueError('Máximo de 5000 registros por projeto')
            if rows: lines.append('-- Registros da tabela ' + tname)
            for r in rows:
                if not isinstance(r, dict): raise ValueError('Registro inválido')
                included = [f for f in fields if f['name'] in r and r[f['name']] not in (None, '')]
                if included:
                    lines.append('INSERT INTO ' + ident(tname) + ' (' + ', '.join(ident(f['name']) for f in included) + ') VALUES (' + ', '.join(sql_literal(r[f['name']], f) for f in included) + ');')
                else: lines.append('INSERT INTO ' + ident(tname) + ' DEFAULT VALUES;')
            if rows: lines.append('')
    # Separe transação de DML antes de alterar metadados (evita object in use).
    lines.append("COMMIT;\n")
    # Firebird 3: após INSERT de IDs explícitos, ajuste a sequência IDENTITY.
    # N + 1 evita colisão em Firebird 3 e 4 (as versões divergem no RESTART WITH).
    for tab in tables:
        for f in tab['fields']:
            if f.get('identity'):
                values = [int(r[f['name']]) for r in tab.get('records', []) if r.get(f['name']) not in (None, '')]
                if values:
                    lines.append('ALTER TABLE ' + ident(tab['name']) + ' ALTER ' + ident(f['name']) +
                                 ' RESTART WITH ' + str(max(1, max(values) + 1)) + ';')
    constraint_names=set()
    for tab in tables:
        tname=rawname(tab['name'])
        for ix in tab.get('indexes', []):
            iname=rawname(ix.get('name'))
            if iname in constraint_names: raise ValueError('Nome de índice duplicado: ' + iname)
            constraint_names.add(iname)
            cols=ix.get('fields', [])
            if not isinstance(cols, list) or not cols: raise ValueError('Índice sem campos')
            for c in cols:
                if rawname(c) not in all_fields[tname]: raise ValueError('Campo de índice inexistente: ' + c)
            lines.append('CREATE ' + ('UNIQUE ' if ix.get('unique') else '') + 'INDEX ' + ident(iname) + ' ON ' + ident(tname) + ' (' + ', '.join(map(ident, cols)) + ');')
        for fk in tab.get('foreignKeys', []):
            fkname=rawname(fk.get('name'))
            if fkname in constraint_names: raise ValueError('Nome de restrição duplicado: ' + fkname)
            constraint_names.add(fkname)
            field=rawname(fk.get('field')); rt=rawname(fk.get('refTable')); rf=rawname(fk.get('refField'))
            if field not in all_fields[tname] or rt not in all_fields or rf not in all_fields[rt]:
                raise ValueError('Relacionamento com campo ou tabela inexistente: ' + fkname)
            action = str(fk.get('onDelete') or 'NO ACTION').upper()
            if action not in DELETE_ACTIONS: raise ValueError('ON DELETE inválido')
            lines.append('ALTER TABLE ' + ident(tname) + ' ADD CONSTRAINT ' + ident(fkname) +
                         ' FOREIGN KEY (' + ident(field) + ') REFERENCES ' + ident(rt) +
                         ' (' + ident(rf) + ') ON DELETE ' + action + ';')
    lines += ['','COMMIT;']
    return '\n'.join(lines) + '\n'

def build_fdb(project):
    sql = schema_sql(project, True)
    with tempfile.TemporaryDirectory(prefix='fb_designer_') as tmp:
        destination = Path(tmp) / 'projeto.fdb'
        script_file = Path(tmp) / 'create.sql'
        create = f"CREATE DATABASE '{destination}' USER SYSDBA PASSWORD 'masterkey' PAGE_SIZE 8192 DEFAULT CHARACTER SET {project.get('charset','UTF8')};\n"
        # Se ocorrer erro, -b cancela sem entregar arquivo incompleto.
        script_file.write_text(create + sql + 'QUIT;\n', encoding='utf-8')
        try:
            p = subprocess.run(['isql-fb', '-b', '-q', '-i', str(script_file)], capture_output=True,
                               text=True, timeout=38, cwd=tmp)
        except FileNotFoundError: raise RuntimeError('Firebird Embedded não está instalado no servidor')
        except subprocess.TimeoutExpired: raise RuntimeError('A criação excedeu o limite de 38 segundos')
        if p.returncode != 0 or 'Statement failed' in (p.stdout + p.stderr):
            # Não expor caminhos do sistema ao usuário.
            error=(p.stderr or p.stdout).splitlines()
            raise ValueError('O Firebird rejeitou a estrutura. ' + ' | '.join(error[-5:])[:400].replace(tmp, '[tmp]'))
        if not destination.exists(): raise RuntimeError('O Firebird não gerou o arquivo')
        size = destination.stat().st_size
        if size > 30_000_000: raise ValueError('O banco gerado excede 30 MB')
        return destination.read_bytes()

class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs): super().__init__(*args, directory=str(ROOT), **kwargs)
    def end_headers(self):
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.send_header('X-Frame-Options', 'DENY')
        self.send_header('Referrer-Policy', 'no-referrer')
        self.send_header('Cache-Control', 'no-store' if self.path.startswith('/api/') else 'public, max-age=180')
        super().end_headers()
    def log_message(self, fmt, *args):
        # Nunca registra JSON, senhas nem dados de registros.
        print('%s - %s' % (self.client_address[0], fmt % args), flush=True)
    def json_send(self, status, obj):
        data=json.dumps(obj, ensure_ascii=False).encode('utf-8')
        self.send_response(status); self.send_header('Content-Type','application/json; charset=utf-8'); self.send_header('Content-Length',str(len(data))); self.end_headers(); self.wfile.write(data)
    def do_GET(self):
        path = urlsplit(self.path).path
        if path == '/api/health':
            return self.json_send(200, {'ok': True, 'fdb': True, 'engine': 'Firebird Embedded 3 (Docker)'})
        # Evita servir código do backend, arquivos de sistema ou configuração.
        if path == '/': self.path='/index.html'
        elif not (path == '/index.html' or path.startswith('/static/')): return self.send_error(404)
        return super().do_GET()
    def do_POST(self):
        if urlsplit(self.path).path != '/api/export-fdb': return self.json_send(404,{'error':'Rota desconhecida'})
        if self.headers.get('Content-Type','').split(';')[0].lower() != 'application/json':
            return self.json_send(415, {'error':'Envie JSON'})
        try: length=int(self.headers.get('Content-Length','0'))
        except ValueError: return self.json_send(400,{'error':'Tamanho inválido'})
        if length < 1 or length > LIMIT_BYTES: return self.json_send(413, {'error':'Projeto muito grande (máximo 2 MB)'})
        ip = self.client_address[0]
        with RATE_LOCK:
            q=RATES[ip]; now=time.monotonic()
            while q and now-q[0] > 60: q.popleft()
            if len(q)>=8: return self.json_send(429,{'error':'Limite de 8 exportações por minuto. Tente novamente.'})
            q.append(now)
        if not SEM.acquire(blocking=False): return self.json_send(503,{'error':'Gerador ocupado. Tente novamente.'})
        try:
            payload=json.loads(self.rfile.read(length))
            project=payload.get('project')
            data=build_fdb(project)
            name=re.sub(r'[^A-Za-z0-9_-]','_',str(project.get('name','MEU_BANCO')))[:50] or 'MEU_BANCO'
            self.send_response(200)
            self.send_header('Content-Type','application/octet-stream')
            self.send_header('Content-Disposition', f'attachment; filename="{name}.fdb"')
            self.send_header('Content-Length',str(len(data)))
            self.end_headers(); self.wfile.write(data)
        except (ValueError, TypeError, KeyError, json.JSONDecodeError) as e: self.json_send(422,{'error':str(e)[:450]})
        except Exception as e: self.json_send(500,{'error':'Falha interna no gerador: '+str(e)[:180]})
        finally: SEM.release()

if __name__ == '__main__':
    port=int(os.environ.get('PORT','10000'))
    print(f'Firebird Designer Online: http://0.0.0.0:{port}', flush=True)
    ThreadingHTTPServer(('0.0.0.0', port), Handler).serve_forever()
